import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

INP_GMM = "/mnt/g/STAR_HPV/processed/state_vectors/kepler_led_state_vector_gmmgate.parquet"

TAIL_Q90 = "/mnt/g/STAR_HPV/results/anchor_catalogs/kepler_ripe_tail_window_q90.parquet"
TAIL_Q95 = "/mnt/g/STAR_HPV/results/anchor_catalogs/kepler_ripe_tail_window_q95.parquet"

OUT_DIR = "/mnt/g/STAR_HPV/results/figures/ripe_tail_window"
OUT_TEX = f"{OUT_DIR}/figures_ripe_tail_window.tex"

BINS_ORDER = ["3200-4000", "4000-5200", "5200-6000", "6000-7500"]

def norm_sid(s):
    return s.astype("string").str.strip().str.replace(r"\.0$", "", regex=True)

def ensure_dir(p):
    os.makedirs(p, exist_ok=True)

