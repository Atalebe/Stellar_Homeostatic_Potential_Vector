#!/usr/bin/env python3
"""
src/45e_plot_variance_scaling_results.py

Plots variance scaling outputs for:
- bp_rp quantile coarse graining (detrended): variance_scaling_bprp_detrended.csv
- rotation-radius coarse graining: variance_scaling_rotation_radius.csv

Outputs:
- figures:
  /mnt/g/STAR_HPV/results/figures/variance_scaling_summary/*.png
- TeX snippet:
  /mnt/g/STAR_HPV/results/figures/variance_scaling_summary/figures_variance_scaling_summary.tex
- YAML manifest:
  /mnt/g/STAR_HPV/results/figures/variance_scaling_summary/figures_variance_scaling_summary.yaml
"""

from __future__ import annotations

import os
import argparse
from typing import Dict, List

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yaml


def ensure_dir(p: str) -> None:
    os.makedirs(p, exist_ok=True)


def variant_label(v: str) -> str:
    return {"observed": "observed", "permute_phi_within_teff": "null"}.get(v, v)


def plot_lines(
    df: pd.DataFrame,
    xcol: str,
    ycol: str,
    labelcol: str,
    title: str,
    xlabel: str,
    ylabel: str,
    outpng: str,
    sort_x: bool = True,
) -> None:
    plt.figure()
    for lab, g in df.groupby(labelcol):
        g = g.copy()
        if sort_x:
            g = g.sort_values(xcol)
        plt.plot(g[xcol], g[ycol], marker="o", linestyle="-", label=str(lab))
    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(outpng, dpi=300)
    plt.xscale("log")
    plt.close()


def write_tex_snippet(tex_path: str, fig_paths: Dict[str, str]) -> None:
    lines: List[str] = []
    lines.append(r"% Auto-generated by src/45e_plot_variance_scaling_results.py")
    lines.append("")
    for key, path in fig_paths.items():
        lines.append(r"\begin{figure}[t]")
        lines.append(r"  \centering")
        lines.append(rf"  \includegraphics[width=0.92\linewidth]{{{path}}}")
        lines.append(rf"  \caption{{{key.replace('_',' ')}.}}")
        lines.append(rf"  \label{{fig:variance_scaling:{key}}}")
        lines.append(r"\end{figure}")
        lines.append("")
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).strip() + "\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bprp-csv", default="/mnt/g/STAR_HPV/results/variance_scaling/variance_scaling_bprp_detrended.csv")
    ap.add_argument("--rot-radius-csv", default="/mnt/g/STAR_HPV/results/variance_scaling/variance_scaling_rotation_radius.csv")
    ap.add_argument("--outdir", default="/mnt/g/STAR_HPV/results/figures/variance_scaling_summary")
    ap.add_argument("--seed", type=int, default=123)
    args = ap.parse_args()

    ensure_dir(args.outdir)
    fig_paths: Dict[str, str] = {}

    # -------------------------
    # 1) bp_rp coarse graining
    # -------------------------
    b = pd.read_csv(args.bprp_csv).copy()
    b["variant2"] = b["variant"].map(variant_label)

    # Pooled curves by K (use mean_var)
    # Pick the metric you actually care about: phi_detrended (best) and Phi_gmm (baseline)
    for metric in ["phi_detrended", "Phi_gmm"]:
        sub = b[(b["metric"] == metric) & (b["variant2"].isin(["observed", "null"]))].copy()
        if sub.empty:
            continue

        pooled = (
            sub.groupby(["variant2", "K"], as_index=False)
               .agg(mean_var=("mean_var", "mean"),
                    mean_mad2=("mean_mad2", "mean"),
                    mean_width=("mean_bin_width", "mean"))
        )

        # Plot variance vs mean bin width
        outpng = os.path.join(args.outdir, f"bprp_pooled_{metric}_var_vs_width.png")
        plot_lines(
            df=pooled.rename(columns={"variant2": "Variant"}),
            xcol="mean_width",
            ycol="mean_var",
            labelcol="Variant",
            title=f"bp_rp coarse graining (pooled): {metric} | mean_var vs mean bin width",
            xlabel="mean bp_rp bin width",
            ylabel="mean within-bin variance",
            outpng=outpng,
        )
        fig_paths[f"bprp_pooled_{metric}_var_vs_width"] = outpng

        # Plot robust variance proxy vs width
        outpng2 = os.path.join(args.outdir, f"bprp_pooled_{metric}_mad2_vs_width.png")
        plot_lines(
            df=pooled.rename(columns={"variant2": "Variant"}),
            xcol="mean_width",
            ycol="mean_mad2",
            labelcol="Variant",
            title=f"bp_rp coarse graining (pooled): {metric} | mean_mad2 vs mean bin width",
            xlabel="mean bp_rp bin width",
            ylabel="mean MAD^2 within-bin",
            outpng=outpng2,
        )
        fig_paths[f"bprp_pooled_{metric}_mad2_vs_width"] = outpng2

    # Per teff bin curves for phi_detrended (most relevant)
    metric = "phi_detrended"
    sub = b[(b["metric"] == metric) & (b["variant2"].isin(["observed", "null"]))].copy()
    if not sub.empty:
        for teff, g in sub.groupby("teff_bin_s"):
            gg = (
                g.groupby(["variant2", "K"], as_index=False)
                 .agg(mean_var=("mean_var", "mean"),
                      mean_width=("mean_bin_width", "mean"))
            )
            outpng = os.path.join(args.outdir, f"bprp_{metric}_perteff_{teff.replace('-','_')}.png")
            plot_lines(
                df=gg.rename(columns={"variant2": "Variant"}),
                xcol="mean_width",
                ycol="mean_var",
                labelcol="Variant",
                title=f"bp_rp coarse graining: {metric} | {teff} | mean_var vs width",
                xlabel="mean bp_rp bin width",
                ylabel="mean within-bin variance",
                outpng=outpng,
            )
            fig_paths[f"bprp_{metric}_perteff_{teff.replace('-','_')}"] = outpng

    # -------------------------
    # 2) rotation-radius curves
    # -------------------------
    r = pd.read_csv(args.rot_radius_csv).copy()
    r["variant2"] = r["variant"].map(variant_label)

    # Pooled curves (mean across teff bins)
    pooled_r = (
        r[r["variant2"].isin(["observed", "null"])]
        .groupby(["variant2", "h_logp"], as_index=False)
        .agg(var_resid=("var_resid", "mean"),
             mad2_resid=("mad2_resid", "mean"),
             neigh_med=("neigh_med", "mean"))
        .sort_values("h_logp")
    )

    outpng = os.path.join(args.outdir, "rotation_radius_pooled_var_vs_h.png")
    plot_lines(
        df=pooled_r.rename(columns={"variant2": "Variant"}),
        xcol="h_logp",
        ycol="var_resid",
        labelcol="Variant",
        title="rotation-radius coarse graining (pooled): Var(r_h) vs h",
        xlabel="radius bandwidth h in log10(P_rot)",
        ylabel="Var(r_h)",
        outpng=outpng,
    )
    fig_paths["rotation_radius_pooled_var_vs_h"] = outpng

    outpng2 = os.path.join(args.outdir, "rotation_radius_pooled_mad2_vs_h.png")
    plot_lines(
        df=pooled_r.rename(columns={"variant2": "Variant"}),
        xcol="h_logp",
        ycol="mad2_resid",
        labelcol="Variant",
        title="rotation-radius coarse graining (pooled): MAD^2(r_h) vs h",
        xlabel="radius bandwidth h in log10(P_rot)",
        ylabel="MAD^2(r_h)",
        outpng=outpng2,
    )
    fig_paths["rotation_radius_pooled_mad2_vs_h"] = outpng2

    # Neighborhood size sanity plot (observed only)
    neigh = pooled_r[pooled_r["variant2"] == "observed"].copy()
    if not neigh.empty:
        plt.figure()
        plt.plot(neigh["h_logp"], neigh["neigh_med"], marker="o", linestyle="-")
        plt.title("rotation-radius coarse graining (pooled): median neighborhood size vs h (observed)")
        plt.xlabel("radius bandwidth h in log10(P_rot)")
        plt.ylabel("mean of teff-bin neigh_med")
        plt.tight_layout()
        outpng3 = os.path.join(args.outdir, "rotation_radius_pooled_neighmed_vs_h.png")
        plt.savefig(outpng3, dpi=200)
        plt.close()
        fig_paths["rotation_radius_pooled_neighmed_vs_h"] = outpng3

    # Per teff curves (Var vs h)
    for teff, g in r[r["variant2"].isin(["observed", "null"])].groupby("teff_bin_s"):
        gg = g.groupby(["variant2", "h_logp"], as_index=False).agg(
            var_resid=("var_resid", "mean"),
            mad2_resid=("mad2_resid", "mean"),
            neigh_med=("neigh_med", "mean"),
        ).sort_values("h_logp")

        outpng = os.path.join(args.outdir, f"rotation_radius_var_perteff_{teff.replace('-','_')}.png")
        plot_lines(
            df=gg.rename(columns={"variant2": "Variant"}),
            xcol="h_logp",
            ycol="var_resid",
            labelcol="Variant",
            title=f"rotation-radius coarse graining: Var(r_h) vs h | {teff}",
            xlabel="radius bandwidth h in log10(P_rot)",
            ylabel="Var(r_h)",
            outpng=outpng,
        )
        fig_paths[f"rotation_radius_var_perteff_{teff.replace('-','_')}"] = outpng

    # -------------------------
    # TeX + YAML
    # -------------------------
    tex_path = os.path.join(args.outdir, "figures_variance_scaling_summary.tex")
    write_tex_snippet(tex_path, fig_paths)

    yaml_path = os.path.join(args.outdir, "figures_variance_scaling_summary.yaml")
    meta = {
        "bprp_csv": args.bprp_csv,
        "rot_radius_csv": args.rot_radius_csv,
        "outdir": args.outdir,
        "outputs": {"tex": tex_path, "yaml": yaml_path, "figures": fig_paths},
    }
    with open(yaml_path, "w", encoding="utf-8") as f:
        yaml.safe_dump(meta, f, sort_keys=False)

    print(f"[OK] wrote figures to {args.outdir}")
    print(f"[OK] wrote TeX snippet {tex_path}")
    print(f"[OK] wrote YAML {yaml_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
